#!/usr/bin/env node
'use strict';
// Generates nro/source/runtime_templates.h from Vesper's verified prebuilt ARM64 FS runtime.
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..', '..');
const {artifacts} = require(path.join(ROOT, 'engine/backend/lib/native/artifacts.cjs'));
const {textSection} = require(path.join(ROOT, 'engine/backend/lib/native/elf-text.cjs'));

function fmtBytes(buf) {
  const lines = [];
  for (let i = 0; i < buf.length; i += 16) {
    const chunk = [];
    for (let j = i; j < Math.min(i + 16, buf.length); j++) {
      chunk.push('0x' + buf[j].toString(16).padStart(2, '0'));
    }
    lines.push('  ' + chunk.join(', '));
  }
  return lines.join(',\n');
}

function main() {
  const {templates} = artifacts();
  const rt = templates.runtime;
  const rtBytes = Buffer.from(rt.code, 'base64');

  // Extract raw .text bytes for call0..call6, allocate, publish (reloc-free template at base 0)
  // Note: the only external relocation in each call stub is `original_tail` (patched at runtime
  // as a B instruction at the `passthrough` symbol offset).
  const stubNames = ['call0', 'call1', 'call2', 'call3', 'call4', 'call5', 'call6', 'allocate', 'publish'];
  const stubs = {};
  for (const name of stubNames) {
    const row = templates[name];
    const obj = Buffer.from(row.object, 'base64');
    // Use base=0, original_tail=0 so the branch placeholder is clean; C code patches the B at `passthrough`
    const code = textSection(obj, 0n, {original_tail: 0n});
    stubs[name] = {code, symbols: row.symbols};
  }

  const out = [];
  out.push('/* Auto-generated by nro/tools/gen_runtime_header.cjs — DO NOT EDIT BY HAND. */');
  out.push('/* SPDX-License-Identifier: GPL-2.0-only */');
  out.push('#pragma once');
  out.push('#include <stdint.h>');
  out.push('#include <stddef.h>');
  out.push('');
  out.push(`#define VESPER_RT_CODE_SIZE ${rtBytes.length}u`);
  out.push('');
  out.push('/* Prebuilt ARM64 resident FS runtime offsets */');
  for (const [sym, off] of Object.entries(rt.offsets).sort((a, b) => a[0].localeCompare(b[0]))) {
    const macro = 'VESPER_RT_OFF_' + sym.toUpperCase();
    out.push(`#define ${macro} ${off}u`);
  }
  out.push('');
  out.push('static const uint8_t VESPER_RT_CODE[VESPER_RT_CODE_SIZE] = {');
  out.push(fmtBytes(rtBytes));
  out.push('};');
  out.push('');

  for (const name of stubNames) {
    const s = stubs[name];
    const U = name.toUpperCase();
    out.push(`/* Bridge stub: ${name} (${s.code.length} bytes) */`);
    out.push(`#define VESPER_STUB_${U}_SIZE ${s.code.length}u`);
    for (const key of ['owner', 'operation', 'result', 'passthrough', 'arg0', 'arg1', 'arg2', 'arg3', 'arg4', 'arg5']) {
      if (s.symbols[key]) {
        out.push(`#define VESPER_STUB_${U}_${key.toUpperCase()} ${s.symbols[key].value}u`);
      }
    }
    out.push(`static const uint8_t VESPER_STUB_${U}[${s.code.length}] = {`);
    out.push(fmtBytes(s.code));
    out.push('};');
    out.push('');
  }

  const outPath = path.join(ROOT, 'nro', 'source', 'runtime_templates.h');
  fs.mkdirSync(path.dirname(outPath), {recursive: true});
  fs.writeFileSync(outPath, out.join('\n') + '\n', 'utf8');
  console.log(`Generated ${outPath} (runtime=${rtBytes.length} bytes, ${Object.keys(rt.offsets).length} symbols, ${stubNames.length} call stubs)`);
}

main();
